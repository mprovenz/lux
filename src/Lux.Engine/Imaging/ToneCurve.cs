    /// <summary>Smooth black-level toe encode e(v) (C1-continuous soft (v-0.005)/(1-0.005)).</summary>
    public static float Toe(float v)
    {
        if (v <= 0.0025f) return 0f;
        if (v < 0.0075f) { float d = v - 0.0025f; return d * d * 100.50251f; }
        return (v - 0.005f) * 1.0050251f;
    }

    // Highlight roll-off: the §7 LUT is defined on [0,1] (1.0 = white point), so a naive Clamp blows every
    // scene value past the white point to pure white — losing all highlight detail/colour (e.g. a sunset sky
    // reaching ~3× white). Instead, values below HlKnee pass through unchanged (midtones stay bit-exact vs
    // the DNG curve) and the highlight range (HlKnee..HlWhite) is linearly compressed into (HlKnee..1], so
    // highlights keep their spread (and roll to display white only past HlWhite). This is the tone-map
    // highlight compression Lumen applies (its DNG carries 2-stop headroom for the same reason).
    public const float HlKnee = 0.6f, HlWhite = 2.6f;

    /// <summary>Highlight shoulder: below HlKnee identity; the range (HlKnee..HlWhite) linearly compresses
    /// into (HlKnee..1]. Applied ratio-preserving (see RgbTone) so highlight hue+saturation survive.</summary>
    public static float HighlightRolloff(float x)
    {
        if (x <= HlKnee) return x;
        float t = MathF.Min((x - HlKnee) / (HlWhite - HlKnee), 1f);
        return HlKnee + (1f - HlKnee) * t;
    }

    /// <summary>1024-bin LUT with linear interpolation; x is the toe-encoded value in [0,1].</summary>
    public static float Lookup(float x)
    {
        float idx = Math.Clamp(x, 0f, 1f) * 1024f;
        int lo = (int)MathF.Floor(idx);
        float fr = idx - lo;
        int hi = Math.Min(lo + 1, 1024);
        return Lut[lo] * (1f - fr) + Lut[hi] * fr;
    }

    /// <summary>sRGB gamma (linear → display).</summary>
    public static float Srgb(float x)
    {
        x = Math.Clamp(x, 0f, 1f);
        return x <= 0.0031308f ? 12.92f * x : 1.055f * MathF.Pow(x, 1f / 2.4f) - 0.055f;
    }
